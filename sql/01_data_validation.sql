-- ============================================================
-- 01_data_validation.sql
-- Project: Purchase-to-Pay Process Mining & Exception Intelligence
-- Database: MySQL 8.0+
-- Purpose:
--   1. Create a raw staging table for the converted BPI 2019 CSV
--   2. Validate row counts, analytical grain, activities and nulls
--   3. Investigate timestamps, duplicate-looking rows and case fields
--
-- IMPORTANT:
--   Do not delete or deduplicate source records in this script.
-- ============================================================

CREATE DATABASE IF NOT EXISTS p2p;
USE p2p;

DROP TABLE IF EXISTS p2p_events_raw;

CREATE TABLE p2p_events_raw (
    event_id                         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id                          VARCHAR(255),
    org_resource                     VARCHAR(255),
    activity                         VARCHAR(255),
    cumulative_net_worth_eur         DECIMAL(20,4),

    -- Keep the original timestamp text because the CSV may contain
    -- timezone suffixes. The generated DATETIME uses the first
    -- YYYY-MM-DD HH:MM:SS portion for repeatable analysis.
    event_timestamp_raw              VARCHAR(64),
    event_timestamp                  DATETIME
        GENERATED ALWAYS AS (
            STR_TO_DATE(
                REPLACE(LEFT(event_timestamp_raw, 19), 'T', ' '),
                '%Y-%m-%d %H:%i:%s'
            )
        ) STORED,

    spend_area                       VARCHAR(255),
    company                          VARCHAR(255),
    document_type                    VARCHAR(255),
    sub_spend_area                   VARCHAR(255),
    purchasing_document              VARCHAR(255),
    purchasing_document_category     VARCHAR(255),
    vendor                           VARCHAR(255),
    item_type                        VARCHAR(255),
    item_category                    VARCHAR(255),
    spend_classification             VARCHAR(255),
    source_system                    VARCHAR(255),
    case_name                        VARCHAR(500),
    gr_based_invoice_verification    VARCHAR(255),
    item                             VARCHAR(255),
    case_id                          VARCHAR(255),
    goods_receipt                    VARCHAR(255),

    PRIMARY KEY (event_id),
    INDEX idx_raw_case_id (case_id),
    INDEX idx_raw_activity (activity),
    INDEX idx_raw_timestamp (event_timestamp),
    INDEX idx_raw_vendor (vendor)
);

-- ============================================================
-- CSV IMPORT
-- ============================================================
